// Builds search tags for every item.
//
//   node tools/build-tags.mjs        (also runs automatically at the end of build-prices.mjs)
//
// Reads   data/prices.js             items, flags, caffeine/protein, flavors
//         tools/tag-rules.mjs        brand + product-type rules, word groups
//         data/tag-edits.csv         your fixes: Item, Add tags, Remove tags (tags separated by ;)
// Writes  data/tags.js               what the app searches (don't edit; it's regenerated)
//         tag-report.md              every item with its brand and tags, for review

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath, pathToFileURL } from "node:url";
import { BRANDS, RULES, SYNONYMS, LOW_CAL, LOW_CAL_TAGS, LOW_CAL_FLAVOR } from "./tag-rules.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRICES = path.join(ROOT, "data", "prices.js");
const EDITS = path.join(ROOT, "data", "tag-edits.csv");
const OUT = path.join(ROOT, "data", "tags.js");
const REPORT = path.join(ROOT, "tag-report.md");

const CHOCOLATE_FLAVOR = /chocolate|mocha|cookies & cream/i;
const WATERY = /water|seltzer/; // Bubbl’r is an energy-flagged water: no "energy drink" tag

function loadPrices() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(PRICES, "utf8"), ctx);
  return ctx.window.PACE_DATA;
}

// Tiny CSV reader (quoted fields allowed).
function readEdits() {
  if (!fs.existsSync(EDITS)) return [];
  const text = fs.readFileSync(EDITS, "utf8").replace(/^﻿/, "");
  const rows = []; let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (ch === '"') q = false; else cell += ch; }
    else if (ch === '"' && cell === "") q = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") { if (ch === "\r" && text[i + 1] === "\n") i++; row.push(cell); rows.push(row); row = []; cell = ""; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const split = (s) => (s || "").split(";").map((t) => t.trim().toLowerCase()).filter(Boolean);
  return rows.slice(1).filter((r) => (r[0] || "").trim())
    .map((r) => ({ item: r[0].trim(), add: split(r[1]), remove: split(r[2]) }));
}

export function buildTags({ quiet = false } = {}) {
  const { items, prices } = loadPrices();
  const flavors = {};
  for (const p of prices) if (p.flavors) flavors[p.item] = (flavors[p.item] || "") + " " + [].concat(p.flavors).join(", ");

  const out = {};
  for (const [name, it] of Object.entries(items)) {
    const lower = name.toLowerCase().replace(/'/g, "’");
    const brandRow = BRANDS.find(([, words]) => words.some((w) => lower.includes(w)));
    const tags = [];
    const add = (...t) => t.forEach((x) => { if (x && !tags.includes(x)) tags.push(x); });

    if (brandRow) add(brandRow[0].toLowerCase(), ...(brandRow[2] || []));
    for (const [re, t] of RULES) if (re.test(lower)) add(...t);

    // From the data
    if (it.category === "Drinks") add("drink");
    if (it.energy && !tags.some((t) => WATERY.test(t))) add("energy drink", "energy");
    if (it.caffeine) add("caffeine");
    if (it.protein || it.highProtein) add("protein");
    if (it.healthy) add("healthy");
    if (CHOCOLATE_FLAVOR.test(flavors[name] || "")) add("chocolate");

    // Low calorie: whole item, or only its diet / zero versions ("variants").
    let lowCal = null;
    const lc = LOW_CAL.find(([re]) => re.test(lower));
    if (lc && (lc[1] === "all" || LOW_CAL_FLAVOR.test(flavors[name] || ""))) {
      lowCal = lc[1];
      add(...LOW_CAL_TAGS);
    }

    out[name] = { brand: brandRow ? brandRow[0] : null, tags, ...(lowCal ? { lowCal } : {}) };
  }

  // Your fixes from data/tag-edits.csv
  const problems = [];
  for (const e of readEdits()) {
    const t = out[e.item];
    if (!t) { problems.push(`tag-edits.csv: no item named “${e.item}”`); continue; }
    t.tags = t.tags.filter((x) => !e.remove.includes(x));
    for (const a of e.add) if (!t.tags.includes(a)) t.tags.push(a);
    // Adding / removing "low calorie" puts the item in / takes it out of the chip.
    if (!t.tags.includes("low calorie")) delete t.lowCal;
    else if (!t.lowCal) t.lowCal = "all";
    t.edited = true;
  }

  fs.writeFileSync(OUT, `/*
  Search tags — generated by tools/build-tags.mjs. Don't edit this file:
  fix tags in data/tag-edits.csv (or the rules in tools/tag-rules.mjs) and rebuild.
*/
window.PACE_TAGS = ${JSON.stringify({ synonyms: SYNONYMS, lowCalFlavor: LOW_CAL_FLAVOR.source, items: out }, null, 1)};
`);

  const lines = Object.entries(out)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([n, t]) => `| ${n} | ${t.brand || "—"} | ${t.tags.join(", ")}${t.lowCal === "variants" ? " (low cal: diet/zero versions only)" : ""}${t.edited ? " ✎" : ""} |`);
  fs.writeFileSync(REPORT, `# Search tags

Generated by \`node tools/build-tags.mjs\` (runs with every price rebuild).
To fix an item, add a row to \`data/tag-edits.csv\`: Item, Add tags, Remove tags
(separate tags with ;). ✎ = item has your edits.

Word groups (searching one finds the others): ${SYNONYMS.map((g) => g.join(" = ")).join(" · ")}

| Item | Brand | Tags |
|---|---|---|
${lines.join("\n")}
`);

  if (!quiet) {
    console.log(`Tagged ${Object.keys(out).length} items → data/tags.js, tag-report.md`);
    for (const p of problems) console.log("  ! " + p);
  }
  return { out, problems };
}

// Run directly: node tools/build-tags.mjs
if (import.meta.url === pathToFileURL(process.argv[1] || "").href) buildTags();
